{-# LANGUAGE QuasiQuotes #-}

-- |
-- Off-chain code generation: prints transpiled Roots as TypeScript modules built on MeshJS
-- and on the vendored TS runtime library (`resources/typescript_template/src/lib/`).
--
-- NOTE: this is a skeleton (see doc/offchain.md, step 3). Imports, structs, literal constants and
-- function signatures are generated; function bodies are emitted as placeholders that throw,
-- until the expression-level mapping is designed (step 5).
module TypeScript.TypeScriptGenerator (generateRoot, generateTopLevel, generateType, generateDataType) where

import Control.Exception (evaluate)
import Data.Text (Text, empty, intercalate, null, pack)
import Move.AST
import Move.Translations.Utils (tryIO, unitType)
import NeatInterpolation (trimming)

-- |
-- Where a generated file lives, which decides the relative paths of its imports.
-- Modules are written to `src/modules/module_<address>/<Module>.ts`, scripts to `src/scripts/<name>.ts`
data FileLocation = InModules | InScripts

-- |
-- Given either a Script or a Module, generates its corresponding TypeScript code,
-- prefixed by the imports every generated file relies on (Mesh data types and the runtime data helpers)
generateRoot :: FilePath -> Root -> IO Text
generateRoot fileName (RModule Module {moduleTopLevels}) =
  tryIO fileName $ evaluate $ generateFile InModules moduleTopLevels
generateRoot fileName (RScript Script {scriptTopLevels}) =
  tryIO fileName $ evaluate $ generateFile InScripts scriptTopLevels

-- |
-- Generates a whole file: the fixed header imports, followed by every non-empty top level.
-- Unused imports are allowed by the template's tsconfig, so the header is always the same
generateFile :: FileLocation -> [TopLevel] -> Text
generateFile location topLevels = join "\n" $ header : filter (not . Data.Text.null) (map (generateTopLevelAt location) topLevels)
  where
    libPath = srcRoot location <> pack "lib/"
    header =
      [trimming|
        // Generated by CardaMove. Do not edit.
        import { Bool, ConStr0, Integer } from "@meshsdk/core";
        import { Data, Void, VOID, int, str } from "${libPath}stdlib/data";
      |]

-- |
-- Given any top level, generates its corresponding TypeScript code,
-- assuming the file is a module (only imports depend on the file location)
generateTopLevel :: TopLevel -> Text
generateTopLevel = generateTopLevelAt InModules

-- |
-- Given any top level and the location of the file it belongs to, generates its TypeScript code.
-- Uses become namespace (and member) imports, structs a Mesh constructor type plus a constructor function
generateTopLevelAt :: FileLocation -> TopLevel -> Text
generateTopLevelAt location (TopLevelUse Use {useAddress, useIdentifier, useAlias, useMembers}) =
  join "" $ namespaceImport : memberImports
  where
    -- Mirrors the folder layout of the Aiken generator: the utils address maps to the runtime library,
    -- any other (already numerical) address to the folder of the generated module
    importPath = case useAddress of
      NamedAddress (Identifier "utils") -> srcRoot location <> pack "lib/utils/" <> packIdent useIdentifier
      _ -> srcRoot location <> pack "modules/" <> moduleFolderName useAddress <> pack "/" <> packIdent useIdentifier
    namespace = maybe (packIdent useIdentifier) packIdent useAlias
    namespaceImport =
      [trimming|
        import * as $namespace from "$importPath";
      |]
    memberImports = case useMembers of
      [] -> []
      _ ->
        [ [trimming|
            import { $members } from "$importPath";
          |]
        ]
      where
        members = intercalate (pack ", ") $ map packMember useMembers
        packMember :: UseMember -> Text
        packMember UseMember {useMemberIdentifier, useMemberUseAlias = Nothing} = packIdent useMemberIdentifier
        packMember UseMember {useMemberIdentifier, useMemberUseAlias = Just alias} = packIdent useMemberIdentifier <> pack " as " <> packIdent alias
-- Friends have no translations
generateTopLevelAt _ (TopLevelFriend _) = empty
generateTopLevelAt _ (TopLevelNamedStruct NamedStruct {namedStructIdentifier, namedStructFields}) =
  generateStruct namedStructIdentifier [(packIdent fieldIdentifier, fieldType) | NamedField {fieldIdentifier, fieldType} <- namedStructFields]
generateTopLevelAt _ (TopLevelPositionalStruct PositionalStruct {positionalStructIdentifier, positionalStructFields}) =
  generateStruct positionalStructIdentifier [(pack ("field_" ++ show i), t) | (i, PositionalField t) <- zip [0 :: Int ..] positionalStructFields]
generateTopLevelAt _ (TopLevelConstant Constant {constantIdentifier, constantType, constantExpression}) =
  [trimming|
    export const $name: $t = $expr;
  |]
  where
    name = packIdent constantIdentifier
    t = generateType constantType
    expr = generateLiteral constantExpression
-- Function declaration
-- Type parameters are dropped: after the TypeWitness and Polymorphism passes they are runtime witnesses and Data
generateTopLevelAt _ (TopLevelFunction Function {functionHasNativeModifier = True}) = error "Native functions are not supported"
generateTopLevelAt _ (TopLevelFunction Function {functionHasNativeModifier = False, functionVisibilityModifier, functionName, functionParameters, functionReturnType}) =
  [trimming|
    ${visibility}function $name($fParams): $fReturn {
      throw new Error("CardaMove: the body of `$name` is not generated yet");
    }
  |]
  where
    visibility = case functionVisibilityModifier of
      Nothing -> empty
      _ -> pack "export "

    name = packIdent functionName
    fParams = intercalate (pack ", ") $ map packFunctionParameter functionParameters

    -- Functions with no return type default to unit
    fReturn = generateType $ maybe unitType id functionReturnType

    packFunctionParameter :: Parameter -> Text
    packFunctionParameter Parameter {parameterIdentifier, parameterType} = packIdent parameterIdentifier <> pack ": " <> generateType parameterType

-- |
-- Generates a Move struct as the TS runtime library does for `Coin`/`Signer`:
-- a `ConStr0` type alias (its on-chain encoding) and a constructor function with the same name
generateStruct :: Identifier -> [(Text, Type)] -> Text
generateStruct structIdent fields =
  [trimming|
    export type $name = ConStr0<[$fieldTypes]>;

    export function $name($params): $name {
      return { constructor: 0, fields: [$fieldNames] };
    }
  |]
  where
    name = packIdent structIdent
    fieldTypes = intercalate (pack ", ") $ map (generateDataType . snd) fields
    params = intercalate (pack ", ") [fieldName <> pack ": " <> generateDataType t | (fieldName, t) <- fields]
    fieldNames = intercalate (pack ", ") $ map fst fields

-- |
-- Generates a literal value. Only literals are supported until the expression mapping is designed,
-- so that literal constants can already be generated
generateLiteral :: Expr -> Text
generateLiteral (ValueLiteral (Address addr)) = pack "str(\"" <> packAddress addr <> pack "\")"
generateLiteral (ValueLiteral (Boolean value)) = if value then pack "true" else pack "false"
generateLiteral (ValueLiteral (Numerical (LiteralIntDec value))) = pack "int(" <> pack (show value) <> pack ")"
generateLiteral (ValueLiteral (Numerical (LiteralIntHex value))) = pack "int(BigInt(\"" <> pack value <> pack "\"))"
generateLiteral expr = error $ "TypeScript generator: expressions other than literals are not supported yet: " ++ show expr

-- |
-- Converts a Type into the TypeScript type of a function-level value (parameters, return values, constants).
-- Following the runtime library, a `bool` is a plain `boolean`; integers are Mesh `Integer`s
generateType :: Type -> Text
generateType (TypeConstructor (LocalNameAccessChain (Identifier "bool")) []) = pack "boolean"
generateType t = generateDataType t

-- |
-- Converts a Type into the TypeScript type of a value that is (part of) Plutus data, e.g. a struct field.
-- Struct types are not generic in TS (every struct is `ConStr0` data), so type arguments are dropped
generateDataType :: Type -> Text
generateDataType (TypeConstructor (LocalNameAccessChain (Identifier "bool")) []) = pack "Bool"
generateDataType (TypeConstructor (LocalNameAccessChain (Identifier "u8")) []) = pack "Integer"
generateDataType (TypeConstructor (LocalNameAccessChain (Identifier "u16")) []) = pack "Integer"
generateDataType (TypeConstructor (LocalNameAccessChain (Identifier "u32")) []) = pack "Integer"
generateDataType (TypeConstructor (LocalNameAccessChain (Identifier "u64")) []) = pack "Integer"
generateDataType (TypeConstructor (LocalNameAccessChain (Identifier "u128")) []) = pack "Integer"
generateDataType (TypeConstructor (LocalNameAccessChain (Identifier "u256")) []) = pack "Integer"
-- Address and Signer are mapped to types of the runtime library
generateDataType (TypeConstructor (LocalNameAccessChain (Identifier "address")) []) = pack "Addr"
generateDataType (TypeConstructor (LocalNameAccessChain (Identifier "signer")) []) = pack "Signer"
generateDataType (TypeConstructor nac _tArgs) = generateNameAccessChain nac
-- Any reference type is mapped to the runtime library `Reference<T>`
generateDataType (TypeImmutableRef rType) = pack "Reference<" <> generateDataType rType <> pack ">"
generateDataType (TypeMutableRef rType) = pack "Reference<" <> generateDataType rType <> pack ">"
-- The unit type () is translated to Void, like in Aiken
generateDataType (TypeTuple []) = pack "Void"
generateDataType (TypeTuple ts) = pack "[" <> intercalate (pack ", ") (map generateType ts) <> pack "]"
generateDataType IntermediateTypeWitnessType = pack "TWitness"
generateDataType IntermediateTypeScopes = pack "CPS"
-- Types that can not be inferred are mapped to an undefined type name, which makes type-checking fail on purpose
generateDataType TypeUnknown = pack "UNKNOWN_TYPE"
generateDataType t@(TypeArrow _ _) = error $ "Unexpected TypeArrow: " ++ show t
generateDataType t@(IntermediateTypeNamedStructDeclaration _ _) = error $ "Unexpected IntermediateTypeNamedStructDeclaration: " ++ show t
generateDataType IntermediateTypeData = pack "Data"

-- |
-- Converts a name access chain into a TypeScript name.
-- Modules are imported as namespaces named after the module (or its alias), so the address is dropped
generateNameAccessChain :: NameAccessChain -> Text
generateNameAccessChain (LocalNameAccessChain ident) = packIdent ident
generateNameAccessChain (AliasedNameAccessChain moduleIdent ident) = packIdent moduleIdent <> pack "." <> packIdent ident
generateNameAccessChain (UnaliasedNameAccessChain _addr moduleIdent ident) = packIdent moduleIdent <> pack "." <> packIdent ident

-- |
-- Relative path from a generated file to the `src/` folder of the TypeScript project
srcRoot :: FileLocation -> Text
srcRoot InModules = pack "../../"
srcRoot InScripts = pack "../"

-- |
-- Name of the folder holding a generated module, the same one the Aiken output uses (`module_<address>`)
moduleFolderName :: Address -> Text
moduleFolderName (NamedAddress addressIdent) = pack "module_" <> packIdent addressIdent
moduleFolderName (NumericalAddress (LiteralIntDec numAddr)) = pack "module_" <> pack (show numAddr)
moduleFolderName (NumericalAddress (LiteralIntHex numAddr)) = pack "module_" <> pack numAddr

-- |
-- Prints an address as the text of its string literal, as the Aiken generator does
packAddress :: Address -> Text
packAddress (NamedAddress ident) = packIdent ident
packAddress (NumericalAddress (LiteralIntDec val)) = pack (show val)
packAddress (NumericalAddress (LiteralIntHex val)) = pack val

-- |
-- Joins multiple code lines as a single Text,
-- adding a custom separator and a newline
join :: String -> [Text] -> Text
join sep = intercalate (pack $ sep ++ "\n")

-- |
-- Maps an Identifier to Text
packIdent :: Identifier -> Text
packIdent (Identifier ident) = pack ident
