{-# LANGUAGE QuasiQuotes #-}

-- |
-- Off-chain counterpart of `Aiken.ValidatorGenerator`: generates `src/entrypoints.ts`,
-- the off-chain entry points of the project, one per Move script.
--
-- NOTE: this is a stub (see doc/offchain.md, step 3). It only re-exports each script;
-- building the transaction (datum, redeemer, outputs) for each entry point is step 6.
module TypeScript.EntryPointGenerator (generateEntryPoints) where

import Aiken.ValidatorGenerator (ScriptMainMetadata (..))
import Data.Text (Text, intercalate, pack)
import NeatInterpolation (trimming)

-- |
-- Given the metadata of every script (as collected for the validator), generates `src/entrypoints.ts`.
-- Each script module is re-exported as a namespace named after the script file
generateEntryPoints :: [ScriptMainMetadata] -> Text
generateEntryPoints metas =
  [trimming|
    // Generated by CardaMove. Do not edit.
    // Off-chain entry points, one per Move script.
    // TODO: build the transaction of each entry point (datum, redeemer, outputs), see doc/offchain.md, step 6
    $exports
    export {};
  |]
  where
    exports = intercalate (pack "\n") $ map packExport metas

    -- `scriptImportPath` is `scripts/<name>`, the same relative path used by the Aiken validator
    packExport :: ScriptMainMetadata -> Text
    packExport ScriptMainMetadata {scriptImportPath} =
      let importPath = pack scriptImportPath
          name = pack $ drop (length "scripts/") scriptImportPath
       in [trimming|
            export * as $name from "./$importPath";
          |]
